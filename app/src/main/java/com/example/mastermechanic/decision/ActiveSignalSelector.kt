package com.example.mastermechanic.decision

/**
 * 「期望集合 → 本轮真正参与匹配的信号名」（T2-1，纯逻辑）。
 *
 * 识别层不再做任何"发现式"搜索：每轮只搜[外部注入的期望集合][ExpectedSignals]，
 * **不外扩、不兜底**。历史口径全部取消（T2-1 收敛）：
 * - 取消「按当前状态自动选子集」（T1-10g）：搜什么由流程注入，不再由识别层按状态猜；
 * - 取消「状态未知 → 全扫」（T1-13）：状态未知时同样只搜期望集合；
 * - 取消「补扫 / 周期兜底」：期望集合就是全部搜索范围。
 *
 * 本类只做两件事：
 * 1. **剔除未标定的期望名**（产物里没有的信号无法匹配，不能记进本轮的搜索量）；
 * 2. **空集原样返回**（= 本轮不搜）——区分"搜了但没命中"与"根本没搜"。
 *
 * 语义约束（红线）：未进入搜索集合的信号**不产生判定记录**，状态机不得把它当作「未命中」
 * （否则离开计数会被"没搜"而非"没命中"推高，见 FR-09 冻结的同类语义）。
 *
 * 不含任何设备绑定常量；信号名来自标定产物。
 */
class ActiveSignalSelector(
    /** 已标定信号名（真正可匹配的全部）。 */
    val known: Set<String>,
) {

    /**
     * 本轮要匹配的信号名集合（顺序按 [expected] 的迭代顺序，结果确定）。
     *
     * @param expected 外部注入的期望信号名（可含未标定名）
     */
    fun select(expected: Set<String>): Set<String> =
        expected.filterTo(LinkedHashSet()) { it in known }
}
