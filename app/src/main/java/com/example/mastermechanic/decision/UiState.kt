package com.example.mastermechanic.decision

/**
 * 界面状态（T1-4，§2.1；术语取值见 glossary，不得增减或改名）。
 *
 * 声明顺序 = 多状态同时命中时的候选优先级：活动弹窗 / 新手引导为 FR-01、FR-02
 * 规定的最高 / 次高优先级（弹窗遮挡画面、阻断识别），其余常规界面按 §2.1
 * 表格顺序排列。[UNKNOWN] 不参与候选（没有任何标志对应「未知」）。
 */
enum class UiState(val label: String) {

    /** 活动弹窗（§2.1）：弹窗关闭控件标志；FR-01 最高优先级。 */
    ACTIVITY_POPUP("活动弹窗"),

    /** 新手大厅 / 新手引导（§2.1）：新手标志；FR-02 次高优先级。 */
    TUTORIAL("新手大厅/新手引导"),

    /** 启动页（§2.1）：「开始游戏」「换区」标志。 */
    LAUNCH_PAGE("启动页"),

    /** 选择服务器（§2.1）：「选择服务器」标志。 */
    SERVER_SELECT("选择服务器"),

    /** 大厅（§2.1）：对战 / 排位 / 农场入口，任一命中即为大厅。 */
    HALL("大厅"),

    /** 农场（§2.1）：农场标志。 */
    FARM("农场"),

    /** 好友列表（§2.1）：好友列表标志。 */
    FRIEND_LIST("好友列表"),

    /** 好友的农场（§2.1）：拜访后进入的农场。 */
    FRIEND_FARM("好友的农场"),

    /** 未知（§2.2）：连续 3 次未命中任何标志；未知不操作。 */
    UNKNOWN("未知"),
    ;

    /** 是否可作为「当前状态」的候选（未知没有标志，不参与候选）。 */
    val isCandidate: Boolean get() = this != UNKNOWN
}
