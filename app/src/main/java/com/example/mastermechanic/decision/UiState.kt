package com.example.mastermechanic.decision

/**
 * 界面状态（T1-4，§2.1；术语取值见 glossary，不得增减或改名）。
 *
 * 声明顺序 = 多状态同时命中时的候选优先级：活动弹窗为 FR-01 规定的最高优先级（弹窗遮挡画面、
 * 阻断识别），其余常规界面按 §2.1 表格顺序排列。[UNKNOWN] 不参与候选
 * （没有任何标志对应「未知」）。
 *
 * **FR-02（新手引导 / 新手大厅）已恢复**（2026-09-29 用户口径，requirements §3.1 的"恢复条件"成立）：
 * 2026-09-13 移除它的前提是"投入使用的账号都先打完一局"；现在确实用到了**全新号**（新手号），
 * 两个界面又出现了 ⇒ 恢复为 [TUTORIAL_GUIDE] / [TUTORIAL_HALL]，处置口径与 FR-01 一致
 * （**看到就点掉它的关闭控件**，见 `PatrolAnchors` 的说明与 `CaptureService.stepPopupClose`），
 * 但不参与跑号流程（[PatrolScenes.read] 读成「被遮挡」）。标定页的归属状态列表直接取本枚举候选。
 *
 * **这里不再有「状态默认信号名」**（2026-09-19 用户口径）：标定产物的元素 ID 改由程序按**语义**取
 * （锚点 = 用途名，其余 = `<界面>_e[n]`，见 `CalibrationSignals.targetFor`），用户不必关心"这条叫什么"；
 * 留着默认名只会让人以为"名字还得人来定"。状态只提供 [label]。
 */
enum class UiState(val label: String) {

    /**
     * 新手引导（FR-02 恢复，2026-09-29）：**只在新手号上出现**，登录之后、活动弹窗之前。
     *
     * 声明在**最前**，两条理由各占一半：
     * 1. 它是**盖在下层界面上的遮挡屏**（和活动弹窗同一族），必须排在 [LAUNCH_PAGE] / [HALL] / [FARM]
     *    之前，否则"人在新手引导上"会被判成"人在启动页 / 大厅"（那两个标志此时多半也在命中），
     *    流程就会照着下层界面去动手；
     * 2. 与 [ACTIVITY_POPUP] 的相对顺序按**时间顺序**定（用户口径 2026-09-29："新手两屏出现在
     *    活动弹窗之前"）—— 先出现的先管：万一两者**同时**命中，先解决新手这屏，再去管弹窗。
     */
    TUTORIAL_GUIDE("新手引导"),

    /**
     * 新手大厅（FR-02 恢复，2026-09-29）：新手号登录后的"简化版大厅"，同样只在新手号出现。
     *
     * 它**不是** [HALL]：新手大厅上没有设置入口、农场入口这些流程要用的东西，读成"大厅"会让第 3/7 步
     * 去找不存在的按钮 ⇒ 同样按"遮挡屏"处理（点掉它的退出 / 跳过控件，露出真正的大厅）。
     * 声明在 [HALL] 与 [ACTIVITY_POPUP] 之前，理由同上（新手这族先出现）。
     */
    TUTORIAL_HALL("新手大厅"),

    /**
     * 活动弹窗（§2.1）：弹窗关闭控件标志；FR-01。
     *
     * ⚠ 它**不再是**枚举里的第一项（2026-09-29）：新手两屏按"先出现先管"排到了它前面。
     * 「弹窗遮挡画面、阻断识别 ⇒ 最高优先级」这个理由本身没变，变的是**同时命中**时的取舍：
     * 新手两屏出现得更早，先解决它们，再回来管弹窗（两者本来也不同时出现）。
     */
    ACTIVITY_POPUP("活动弹窗"),

    /** 启动页（§2.1）：「开始游戏」「换区」标志。 */
    LAUNCH_PAGE("启动页"),

    /** 服务器列表（§2.1）：「选择服务器」标志。 */
    SERVER_SELECT("服务器列表"),

    /**
     * 退出登录确认框（§2.1，2026-09-19 新增）：确认弹窗的标志。
     *
     * 声明在 [HALL_SETTINGS] 与 [HALL] 之前：它是叠在设置页上的弹窗，
     * 两处标志同时命中时要让更"上层"的那个赢（声明顺序 = 候选优先级）。
     */
    LOGOUT_CONFIRM("退出登录确认框"),

    /**
     * 设置页（§2.1，2026-09-19 新增）：游戏内设置界面的标志。
     *
     * 它是大厅的子界面（从大厅的设置入口进来），标志会与大堂同时命中 →
     * 同样必须声明在 [HALL] 之前，否则"人在设置页"会被判成"人在大厅"，
     * 退出登录那一步就会去点大厅里的设置入口（点不动）。
     */
    HALL_SETTINGS("设置页"),

    /** 大厅（§2.1）：对战 / 排位 / 农场入口，任一命中即为大厅。 */
    HALL("大厅"),

    /**
     * 返回场景确认框（§2.1，2026-09-19 新增）：农场 / 好友的农场点左上角返回后弹出的
     * 「提示：请选择需要返回的场景」弹框（按钮 =「返回稷下学院」/「返回大厅」）。
     *
     * 声明在 [FARM] / [FRIEND_FARM] 之前：它叠在农场画面上，两处标志同时命中时更上层的要赢。
     * 少了这一屏，「退出农场」就无从验证（点了返回之后到底进没进大厅只能猜）。
     */
    SCENE_RETURN_CONFIRM("返回场景确认框"),

    /**
     * 农场（§2.1）：农场标志。
     *
     * ## 与 [FRIEND_LIST] 的优先级（2026-09-22 真机踩过一轮）
     *
     * 曾把 `FRIEND_LIST` 提到本项之前（理由是"列表是浮层、更上层"，理论上对），
     * 但真机立刻变得更糟：**农场的标志本来就弱**（用户目前只框了"好友"按钮，
     * 32×32 且会随列表开合被遮挡），而"好友列表标志"反而**在农场画面上也命中**
     * ⇒ 列表优先的结果是**人在农场却被判成"好友列表"**，起步判定一律拦住。
     *
     * 结论：**优先级要按"哪个标志更可靠"定，不是按层级**。当前农场的标志最弱，
     * 所以**农场保持优先**——至少"列表标志误命中"不会把"确实在农场"压掉。
     * 等农场多框几条稳定标志、且列表标志换成列表独有元素之后，再重新评估这个顺序。
     */
    FARM("农场"),

    /** 好友列表（§2.1）：好友列表标志。 */
    FRIEND_LIST("好友列表"),

    /** 好友的农场（§2.1）：拜访后进入的农场。 */
    FRIEND_FARM("好友的农场"),

    /** 未知（§2.2）：连续 3 次未命中任何标志；未知不操作，也没有标志。 */
    UNKNOWN("未知"),
    ;

    /** 是否可作为「当前状态」的候选（未知没有标志，不参与候选）。 */
    val isCandidate: Boolean get() = this != UNKNOWN

    companion object {

        /**
         * **需要"任何阶段看到就自动点掉它的关闭控件"的遮挡屏**（2026-09-29 加）：
         * FR-02 新手引导 / 新手大厅 + FR-01 活动弹窗（**按声明顺序 = 出现顺序**：新手两屏先出现）。
         *
         * 这三屏的共同点：**盖在别的界面上、挡住识别、自身不代表任何可跑的场景**，且都有一个
         * "点一下就消失"的控件。凡是按这个语义写的代码，都应当取本集合而不是硬写某个状态
         * —— 三处必须一致（少一处就出问题，且都不会报错、只会静默失效）：
         * 1. 识别层**恒定搜索它们的标志**（`PopupWatchExpectedSignals`）⇒ 否则永远认不出；
         * 2. 锚点窗口的**灰度转换集合**（`CaptureService.anchorRegions`）⇒ 否则锚点读到全零、静默 miss；
         * 3. **关闭闭环的触发条件**（`CaptureService.stepPopupClose`）⇒ 否则决策根本不跑。
         */
        val guardedOverlays: List<UiState> = listOf(TUTORIAL_GUIDE, TUTORIAL_HALL, ACTIVITY_POPUP)
    }
}
