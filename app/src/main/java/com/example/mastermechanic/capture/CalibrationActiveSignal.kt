package com.example.mastermechanic.capture

/**
 * **标定工作台正在前台**（2026-09-29 加）：采集侧据此**暂停取帧并释放帧缓冲**。
 *
 * ## 为什么需要它（真机："开始一段时间点框选正常，过一段时间再点就黑屏崩溃"）
 *
 * 打开框选 = 一个**全屏 Dialog** + 解码一张预览 + 画几十个缩略图 ⇒ 那一刻要吃掉几十 MB。
 * 而采集还同时攥着：两块帧复用缓冲（3168×1440×4 ≈ 18MB × 2）、兜底缓存那一帧、本轮的灰度与签名
 * ⇒ 两者相加就把 268MB 的堆顶爆 ⇒ 界面画不出来（黑屏）⇒ ANR ⇒ 被杀。
 *
 * 而**工作台开着的时候，采集是没有意义的**：
 * - 本 App 在前台 ⇒ 镜像里根本不是游戏画面；
 * - 标定用的是**帧池里已存的帧**（`CalibrationFramePool`），不是实时画面；
 * - 「录制」也是靠游戏在前台跑才录得到 —— 工作台盖住屏幕期间录不到任何东西。
 *
 * ⇒ 工作台一打开就：取到的帧**立刻 close 并丢弃**（不缓存、不处理、不录制），并**释放**帧缓冲
 * 与兜底缓存；工作台一关，下一帧照常恢复（缓冲按需重建）。
 *
 * 只在 UI 线程写、帧线程读 ⇒ 用 [@Volatile]。
 */
object CalibrationActiveSignal {

    @Volatile
    var active: Boolean = false
        private set

    /** 工作台打开 / 关闭时调用（幂等）。 */
    fun update(active: Boolean) {
        this.active = active
    }
}
